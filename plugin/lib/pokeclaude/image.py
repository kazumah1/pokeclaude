"""A tiny raster canvas and PNG encoder, for hosts that show images but not colour.

Some agent GUIs strip ANSI escapes out of a hook's output and collapse what is
left behind a disclosure triangle -- which happens to be the exact two things
pixel art cannot survive. Those GUIs (Kiro, Cursor) are VS Code forks, and a
VS Code fork opens a PNG in a real image editor tab. So on those hosts the art is
drawn as an actual image and handed to the editor, rather than pushed through a
text stream that will mangle it.

Stdlib only, deliberately. PokeClaude installs with one command and a `pip
install pillow` would turn a Pokemon into a build step; 70 lines of encoder is
the cheaper side of that trade. The output is 8-bit truecolour, non-interlaced,
filter type 0 -- the simplest PNG that exists, and small enough after zlib that
a catch card lands around 20KB.
"""
import binascii
import struct
import zlib

# --- PNG ---------------------------------------------------------------------

_MAGIC = b"\x89PNG\r\n\x1a\n"


def _chunk(tag, data):
    return (
        struct.pack(">I", len(data))
        + tag
        + data
        + struct.pack(">I", binascii.crc32(tag + data) & 0xFFFFFFFF)
    )


def encode_png(width, height, rows):
    """Encode RGB rows (each `width` * 3 bytes) as PNG bytes.

    Every scanline is prefixed with filter type 0 (None). Real encoders pick a
    filter per row to help compression, but a catch card is flat colour over a
    flat background -- the kind of image zlib already crushes -- so the extra
    machinery would buy a couple of KB and cost a page of code.
    """
    raw = b"".join(b"\x00" + bytes(r) for r in rows)
    return (
        _MAGIC
        + _chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + _chunk(b"IDAT", zlib.compress(raw, 6))
        + _chunk(b"IEND", b"")
    )


