# One blank column between glyphs, so a run of text does not fuse together.
ADVANCE = GLYPH_W + 1


def text_width(s, scale=1):
    """Pixels `s` occupies, trailing letter-space excluded."""
    if not s:
        return 0
    return (len(s) * ADVANCE - 1) * scale


class Canvas(object):
    """A fixed-size RGB pixel buffer with the few primitives a card needs."""

    def __init__(self, width, height, bg=(0, 0, 0)):
        self.w = width
        self.h = height
        self.rows = [bytearray(bytes(bg) * width) for _ in range(height)]

    def set(self, x, y, rgb):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = x * 3
            self.rows[y][i:i + 3] = bytes(rgb)

    def rect(self, x, y, w, h, rgb):
        px = bytes(rgb) * max(0, min(w, self.w - x))
        if not px:
            return
        for yy in range(max(0, y), min(self.h, y + h)):
            i = max(0, x) * 3
            self.rows[yy][i:i + len(px)] = px

    def text(self, x, y, s, rgb, scale=1):
        """Draw `s` with its top-left at (x, y). Returns the width drawn."""
        for n, ch in enumerate(s.upper()):
            glyph = FONT.get(ch)
            if not glyph:
                continue
            gx = x + n * ADVANCE * scale
            for row, bits in enumerate(glyph):
                if not bits:
                    continue
                for col in range(GLYPH_W):
                    if bits & (1 << (GLYPH_W - 1 - col)):
                        self.rect(gx + col * scale, y + row * scale, scale, scale, rgb)
        return text_width(s, scale)

    def to_png(self):
        return encode_png(self.w, self.h, self.rows)
